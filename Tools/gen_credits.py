"""Regenerate CREDITS.md from SourceAssets/manifest.json:  python Tools/gen_credits.py"""
import collections, json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
E = json.load(open(os.path.join(ROOT, 'SourceAssets', 'manifest.json'), encoding='utf-8'))['assets']
LIC = {'CC0-1.0': '[CC0 1.0](https://creativecommons.org/publicdomain/zero/1.0/)', 'OFL-1.1': '[SIL OFL 1.1](https://openfontlicense.org)',
       'CC-BY-4.0': '[CC BY 4.0](https://creativecommons.org/licenses/by/4.0/)'}
out = ['# Credits', '',
       'NO SECOND CHANCE (Unreal Engine 5 build) uses only assets that are free for commercial use and redistribution.',
       'Every file under `SourceAssets/` is listed with its source in `SourceAssets/manifest.json` (generated by `Tools/curate_assets.py`).',
       'No NC/ND-licensed or ripped assets are used. CC0 needs no attribution, but credit is given anyway.', '',
       'Licenses used: ' + ', '.join(sorted({LIC.get(e['license'], e['license']) for e in E})) + '.', '']
ai = [e for e in E if e.get('aiGenerated') or 'AI' in (e.get('author') or '') or '3dassets.dev' in (e.get('source') or '')]
groups = collections.OrderedDict()
for t, title in [('character', 'Characters & animation'), ('weapon', 'Weapons'), ('attachment', 'Weapon attachments'), ('model', 'Props (Poly Haven)'),
                 ('prop', 'Props & gear (3dassets.dev)'), ('texture', 'Textures, decals & FX'), ('hdri', 'HDRIs (Poly Haven)'), ('sound', 'Audio'), ('font', 'Fonts')]:
    rows = [e for e in E if e.get('type') == t]
    if not rows: continue
    out += ['## ' + title, '', '| Asset | Author | Source | License |', '|---|---|---|---|']
    for e in sorted(rows, key=lambda e: (e.get('author') or '', e['name'])):
        src = e.get('source') or ''
        m = re.match(r'(https?://\S+)(.*)', src)
        link = '[%s](%s)%s' % (re.sub(r'^https?://(www\.)?', '', m.group(1)).rstrip('/'), m.group(1), m.group(2)) if m else src
        name = e['name'] + (' *(model: %s)*' % e['original'].replace(' (stand-in)', '') if e.get('original') and e['original'] != e['name'] and t == 'weapon' else '')
        out.append('| %s | %s | %s | %s |' % (name, e.get('author', ''), link, LIC.get(e['license'], e['license'])))
    out.append('')
out += ['## AI-generated / AI-assisted assets', '',
        'These are published as CC0 by their authors but were made with AI tools; they are placeholders you may want to replace:', '']
out += ['* %s — %s (%s)' % (e['name'], e.get('author', ''), e.get('source', '')) for e in ai]
out += ['', '## Launcher & tools', '',
        '* Launcher: [Electron](https://www.electronjs.org) (MIT), [electron-builder](https://www.electron.build) (MIT), [yauzl](https://github.com/thejoshwolfe/yauzl) (MIT).',
        '* Launcher font: [Barlow / Barlow Condensed](https://fonts.google.com/specimen/Barlow) by Jeremy Tribby (SIL OFL 1.1). Launcher hero image: Poly Haven "Empty Warehouse 01" HDRI by Sergej Majboroda (CC0).',
        '* Asset processing: [Blender](https://www.blender.org) (GPL, used as a tool only), [glTF-Transform](https://gltf-transform.dev) (MIT), FFmpeg (tool only).',
        '* Engine: Unreal Engine 5 — © Epic Games, used under the [Unreal Engine EULA](https://www.unrealengine.com/eula). Optional packs you download yourself (Lyra, Paragon, Fab free content) stay under their Fab / Epic Content license and are not redistributed in this repo.', '']
open(os.path.join(ROOT, 'CREDITS.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('CREDITS.md: %d assets, %d AI-flagged' % (len(E), len(ai)))
