def merge_manifests():
    for name in ['polyhaven.json', '3dassets.json']:
        p = os.path.join(SA, '_manifests', name)
        if not os.path.exists(p): continue
        for e in json.load(open(p)):
            files = [f.replace('SourceAssets/', '', 1) for f in (e.get('files') or ([e['file']] if 'file' in e else []))]
            MANIFEST.append(dict(name=e.get('name') or e.get('title'), type=e.get('kind') or e.get('type', 'prop'), files=files,
                                 source=e.get('source') or e.get('url'), author=e.get('author'), license=e.get('license', 'CC0-1.0'),
                                 **({'aiGenerated': True} if e.get('aiGenerated') else {})))

