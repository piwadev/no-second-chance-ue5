def to_wav(srcs, dst, gain_db=0.0):
    """Convert (and concatenate) sources into one 44.1 kHz 16-bit WAV."""
    ensure(os.path.dirname(dst))
    if len(srcs) == 1:
        cmd = ['ffmpeg', '-y', '-loglevel', 'error', '-i', srcs[0], '-af', f'volume={gain_db}dB', '-ar', '44100', '-sample_fmt', 's16', dst]
    else:
        ins = []
        for s in srcs: ins += ['-i', s]
        chain = ''.join(f'[{i}:a]aresample=44100,aformat=channel_layouts=stereo[a{i}];' for i in range(len(srcs)))
        chain += ''.join(f'[a{i}]' for i in range(len(srcs))) + f'concat=n={len(srcs)}:v=0:a=1,volume={gain_db}dB[o]'
        cmd = ['ffmpeg', '-y', '-loglevel', 'error'] + ins + ['-filter_complex', chain, '-map', '[o]', '-sample_fmt', 's16', dst]
    subprocess.run(cmd, check=True)
    return dst

def gen(dst, expr):
    ensure(os.path.dirname(dst))
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-f', 'lavfi', '-i', expr, '-ar', '44100', '-sample_fmt', 's16', dst], check=True)
    return dst

