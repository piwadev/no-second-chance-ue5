def rel(p): return os.path.relpath(p, SA).replace('\\', '/')

def add(name, kind, files, src, **extra):
    e = dict(name=name, type=kind, files=[rel(f) for f in files])
    e.update(SRC[src]); e.update(extra)
    MANIFEST.append(e)

def first(pattern):
    m = sorted(glob.glob(os.path.join(RAW, pattern), recursive=True))
    if not m:
        raise FileNotFoundError(pattern)
    return m[0]

def all_of(pattern):
    return sorted(glob.glob(os.path.join(RAW, pattern), recursive=True))

def ensure(d):
    os.makedirs(d, exist_ok=True); return d

def gltf_clean(src, dst):
    """Decode meshopt / quantization / webp so Unreal's glTF importer reads it."""
    tmp = dst + '.tmp.glb'
    subprocess.run(['npx', '-y', '@gltf-transform/cli', 'dequantize', src, tmp], check=True, capture_output=True)
    subprocess.run(['npx', '-y', '@gltf-transform/cli', 'png', tmp, dst, '--formats', '*'], check=False, capture_output=True)
    if not os.path.exists(dst):
        shutil.move(tmp, dst)
    elif os.path.exists(tmp):
        os.remove(tmp)

def load_gray(path, size, default):
    if path and os.path.exists(path):
        return Image.open(path).convert('L').resize(size)
    return Image.new('L', size, default)

def pack_orm(out, size, ao=None, rough=None, metal=None, defaults=(255, 140, 0)):
    o = load_gray(ao, size, defaults[0]); r = load_gray(rough, size, defaults[1]); m = load_gray(metal, size, defaults[2])
    Image.merge('RGB', (o, r, m)).save(out)

